export const getTranslation = (language, key, fallback = '') => {
  if (!key) return fallback;
  const langLower = (language || 'english').toLowerCase();
  let code = 'en';
  if (langLower.includes('sinhala') || langLower === 'si') code = 'si';
  else if (langLower.includes('tamil') || langLower === 'ta') code = 'ta';
  else if (langLower.includes('spanish') || langLower === 'es') code = 'es';
  else if (langLower.includes('french') || langLower === 'fr') code = 'fr';
  else if (langLower.includes('german') || langLower === 'de') code = 'de';
  else if (langLower.includes('arabic') || langLower === 'ar') code = 'ar';
  else if (langLower.includes('urdu') || langLower === 'ur') code = 'ur';

  return translations[code]?.[key] || translations['en']?.[key] || fallback || key;
};
